import os
import streamlit as st
from database import Database
from utils.session import restore_session
from utils.navigation import setup_page
from config import get_config

st.set_page_config(
    page_title="Система аттестации",
    page_icon="🎓",
    layout="wide",
    initial_sidebar_state="expanded",
)

restore_session()

@st.cache_resource
def get_db():
    return Database()

db = get_db()
cfg = get_config()

for key, default in [
    ("authenticated", False),
    ("user", None),
    ("user_id", None),
    ("role", None),
    ("full_name", None),
]:
    if key not in st.session_state:
        st.session_state[key] = default

# Сайдбар (логин + навигация) + кнопка скрытия
setup_page()

# =========================================================
# ГЛАВНАЯ СТРАНИЦА = ПОМОЩНИК
# =========================================================
st.caption(f"v{cfg.APP_VERSION}")

if st.session_state.authenticated:
    st.title(f"👋 Добро пожаловать, {st.session_state.full_name or st.session_state.user}!")
else:
    st.title("🎓 Система аттестации")

st.caption("Краткая инструкция по работе с системой. Разделы доступны в боковой панели 👈")

st.divider()

tab_common, tab_user, tab_staff = st.tabs(["🌐 Общее", "👤 Для сотрудников", "⚙️ Для администраторов и методистов"])

with tab_common:
    st.markdown("""
    ### Как устроена система
    Система предназначена для проведения тестирования (аттестации) сотрудников. 
    Все действия происходят внутри соответствующих разделов в левом боковом меню.

    **🔐 Вход в систему**
    *   Логин и пароль выдает ваш администратор или методист.
    *   Если вы забыли пароль, обратитесь к администратору для сброса.

    **📱 Навигация**
    *   Слева в меню отображаются только те разделы, к которым у вас есть доступ.
    *   Кнопка `◀️` / `▶️` в левом верхнем углу позволяет скрыть или показать боковую панель.
    *   Кнопка `🚪 Выйти` в самом низу меню завершает сессию.
    """)

with tab_user:
    st.markdown("""
    ### Инструкция для сотрудников (тестируемых)

    **📝 Как пройти тест**
    1. Перейдите в раздел **«📝 Тестирование»**.
    2. В блоке «Активные задания» найдите назначенный вам тест (там будет указано название, дедлайн и количество попыток).
    3. Нажмите кнопку **«▶️ Начать»**.
    4. Отвечайте на вопросы, используя переключатели. Вы можете возвращаться к предыдущим вопросам с помощью кнопки «⬅️ Назад».
    5. После ответа на последний вопрос нажмите **«Завершить ✅»**.

    **⏳ Таймер**
    Если на задание установлено ограничение по времени, в правом верхнем углу будет идти таймер. Когда время закончится, тест сохранится автоматически.

    **📊 Где посмотреть результаты**
    *   Перейдите в раздел **«📊 Результаты»**.
    *   Там отображается ваша личная история: график среднего балла, таблица всех попыток и оценка.
    *   *Обратите внимание: детальный разбор ответов (какой вариант был правильным) доступен только методистам. Вы увидите только итоговый балл.*
    """)

with tab_staff:
    st.markdown("""
    ### Инструкция для администраторов и методистов

    **👥 Управление группами**
    *   Перейдите в **«👥 Группы обучения»**.
    *   Здесь можно создать новую группу, добавить участников вручную или импортировать список из Excel.
    *   Нажмите **«👤 Состав»** у нужной группы, чтобы перейти к управлению её участниками.

    **📄 Мастер заявок (Автоматизация)**
    *   Перейдите в **«📄 Мастер заявок»**.
    *   Скачайте утвержденный шаблон заявки (Word) вверху страницы.
    *   Заполните его и загрузите обратно. Система сама распознает организацию, контакты и список сотрудников.
    *   Проверьте данные и нажмите «🚀 Создать группу и задание».

    **📌 Назначение тестов**
    *   Перейдите в раздел **«📌 Задания»**.
    *   Нажмите «➕ Создать новое задание», выберите группу, тему и настройте параметры (проходной балл, количество попыток, дедлайн).
    *   В карточке задания вы можете посмотреть детали (кто сдал, а кто нет), закрыть задание или отредактировать его.

    **🎯 Прохождение теста за сотрудника (Сурогат)**
    *   Если у сотрудника нет доступа к компьютеру, перейдите в **«🎯 Режим сурогата»**.
    *   Выберите группу и сотрудника, нажмите «Начать тест». Результат сохранится в профиль этого сотрудника.

    **👨‍🏫 Кабинет методиста (Вопросы)**
    *   В разделе **«👨‍🏫 Кабинет методиста»** вы управляете банком вопросов.
    *   Можно добавлять вопросы вручную, импортировать их из CSV/JSON или выгружать.
    *   Вкладка «Статистика» покажет, на какие вопросы сотрудники отвечают хуже всего.
    """)